import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pack, validate, receive } from '../scripts/ready-package.mjs';

test('ready packages keep matching source and app; reject damage before replacing the app', t => {
  const scratch = mkdtempSync(join(tmpdir(), 'helm-ready-'));
  t.after(() => rmSync(scratch, { recursive: true, force: true }));
  const root = join(scratch, 'repo'), output = join(scratch, 'package');
  mkdirSync(root);
  const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' }).trim();
  git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  writeFileSync(join(root, '.gitignore'), 'apps/web/dist/\n');
  git('add', '.'); git('commit', '-qm', 'Fixture');
  const commit = git('rev-parse', 'HEAD');
  const web = join(root, 'apps/web/dist'); mkdirSync(web, { recursive: true });
  writeFileSync(join(web, 'index.html'), '<html>Built app</html>');
  const stamp = { commit, dirty: false };
  writeFileSync(join(web, 'build.json'), JSON.stringify(stamp));
  writeFileSync(join(web, 'index.html'), '<script src="/assets/missing.js"></script>');
  assert.throws(() => pack(root, output), /missing asset/);
  writeFileSync(join(web, 'index.html'), '<html>Built app</html>');
  pack(root, output);
  assert.equal(validate(output, root).commit, commit);
  writeFileSync(join(web, 'index.html'), 'Old app');
  receive(output, root);
  assert.equal(readFileSync(join(web, 'index.html'), 'utf8'), '<html>Built app</html>');
  writeFileSync(join(output, 'web/index.html'), 'Damaged');
  assert.throws(() => receive(output, root), /file changed/);
  assert.equal(readFileSync(join(web, 'index.html'), 'utf8'), '<html>Built app</html>');
  writeFileSync(join(output, 'web/index.html'), '<html>Built app</html>');
  writeFileSync(join(output, 'extra'), 'unexpected');
  assert.throws(() => validate(output, root), /file list/);
  rmSync(join(output, 'extra'));
  symlinkSync(join(web, 'index.html'), join(output, 'web/link'));
  assert.throws(() => validate(output, root), /links/);
  rmSync(join(output, 'web/link'));
  writeFileSync(join(root, 'unsaved'), 'Keep me');
  assert.throws(() => receive(output, root), /local changes/);
  assert.throws(() => pack(root, join(scratch, 'dirty')), /local changes/);
  rmSync(join(root, 'unsaved'));
  writeFileSync(join(root, 'next'), 'Next source'); git('add', '.'); git('commit', '-qm', 'Next');
  assert.throws(() => receive(output, root), /Update the source/);
  assert.throws(() => pack(root, join(scratch, 'old')), /clean commit/);
});
